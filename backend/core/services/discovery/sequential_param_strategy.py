import logging
from typing import Any, Dict, Optional
from urllib.parse import urlparse, parse_qs, urlencode

from .base import DiscoveryStrategy
from .utils import fetch_page

try:
    from backend.core.services.ai_pipeline import MediaDiscovery, AudioExtractor
except ModuleNotFoundError:
    from core.services.ai_pipeline import MediaDiscovery, AudioExtractor

logger = logging.getLogger("AIPipeline")

MAX_SEQUENTIAL_ITEMS = 25  # safety cap, matches NavLinkStrategy's chain limit


class SequentialQueryParamStrategy(DiscoveryStrategy):
    """
    Strategy: a numbered-sequence query parameter (e.g. ?seq_num=0), where
    each value serves genuinely different embedded media rather than a
    stable "page N of a fixed list" -- confirmed directly against
    speech.intron.health's practice-clip queue, 2026-08-03.

    Deliberately NOT in the default STRATEGIES list in engine.py -- this is
    opt-in only, appended by discover() when try_sequential=True is passed
    explicitly. Unlike every other strategy here, walking this pattern can
    have real side effects on the source site (confirmed: re-fetching the
    same index returned DIFFERENT content, implying server-side state
    advances per-request); auto-probing every numeric query parameter on
    every generic URL by default would silently consume state on sites
    where that's never wanted.

    Only fetches twice during discovery (the given index and the next one,
    to confirm the pattern is real -- different embedded audio at each)
    rather than pre-fetching the whole proposed range: the remaining item
    URLs are generated by incrementing the same parameter and are only
    actually fetched later, if and when the user chooses to process them
    (same as how a YouTube playlist's items are just URLs until each one's
    own transcription job runs).
    """

    name = "sequential_query_param"

    def discover(self, url: str, extra_headers: Optional[Dict[str, str]] = None,
                 html: Optional[str] = None) -> Optional[Dict[str, Any]]:
        if MediaDiscovery.classify(url) != "generic":
            return None

        parsed = urlparse(url)
        query = parse_qs(parsed.query, keep_blank_values=True)
        numeric_params = [k for k, v in query.items() if v and v[0].isdigit()]
        if len(numeric_params) != 1:
            # Ambiguous (zero or multiple numeric params) -- don't guess
            # which one, if any, is a sequence index.
            return None
        param_name = numeric_params[0]
        start_value = int(query[param_name][0])

        def build_url(index_value: int) -> str:
            new_query = {k: v[0] for k, v in query.items()}
            new_query[param_name] = str(index_value)
            return f"{parsed.scheme}://{parsed.netloc}{parsed.path}?{urlencode(new_query)}"

        # Confirm the pattern before committing to it: fetch the given
        # index and the next one, and check they surface different
        # embedded audio -- otherwise this numeric parameter is more
        # likely a stable ID, a cache-buster, or something else entirely,
        # not a content-advancing sequence.
        html_a = html or fetch_page(url, extra_headers=extra_headers)
        if not html_a:
            return None
        audio_a = AudioExtractor._find_embedded_audio_url(html_a, url)
        if not audio_a:
            return None

        next_url = build_url(start_value + 1)
        html_b = fetch_page(next_url, extra_headers=extra_headers)
        if not html_b:
            return None
        audio_b = AudioExtractor._find_embedded_audio_url(html_b, next_url)
        if not audio_b or audio_b == audio_a:
            return None

        logger.info(f"Sequential query-param pattern confirmed for '{url}' via '{param_name}'")
        items = [
            {"url": build_url(start_value + i), "title": f"Item {i + 1}"}
            for i in range(MAX_SEQUENTIAL_ITEMS)
        ]
        return {"items": items, "current_index": 0}

<#
    The poller, as a Windows scheduled task.

    WHY THIS EXISTS. Until now the poller has only ever run inside a
    terminal someone left open. Close the window, reboot, or let the machine
    sleep, and the queue silently stops updating -- it does not empty or
    error, it just freezes at whatever it last saw. A worker can then claim a
    task that Eagle gave to someone else hours ago.

    This is the stop-gap for the development machine. The real answer is
    deploy/eagle-cycle.service on a box with a static IP, which also fixes
    the Cloudflare clearance expiring every few hours on a mobile
    connection.

    RUN AS ADMINISTRATOR:
        powershell -ExecutionPolicy Bypass -File deploy\install-windows-task.ps1

    THEN:
        Get-ScheduledTask EagleCycle | Get-ScheduledTaskInfo
        Get-Content "$env:PROGRAMDATA\transcription\eagle-cycle.log" -Tail 40 -Wait

    REMOVE:
        Unregister-ScheduledTask EagleCycle -Confirm:$false
#>

[CmdletBinding()]
param(
    # Repository root. Resolved in the body, not here: $PSScriptRoot is not
    # reliably populated inside a param block under Windows PowerShell 5.1,
    # and an empty default fails with a message about Split-Path rather than
    # about the thing that is actually missing.
    [string] $ProjectRoot,

    [string] $TaskName = 'EagleCycle',

    # Seconds between cycles. 90 keeps the Eagle session alive comfortably
    # inside Laravel's ~2 hour idle timeout without hammering the platform.
    [int] $IntervalSeconds = 90,

    # HOW MANY TASKS TO KEEP READY. Warming spends no platform minutes, so
    # the only cost of warming a task somebody else takes is CPU that was
    # otherwise idle. Measured on a live day: a 44-task drop was gone in
    # about four hours and 75% of the translation work went to other
    # people's taskers, so a pool of 3 is permanently behind.
    [int] $PoolSize = 24,

    # A MEMORY BUDGET, NOT A SPEED DIAL: roughly 750 MB per model-bearing
    # pipeline. 2 wants ~1.5 GB free and warms a task about every 50
    # seconds. Raise it only if this machine has the headroom.
    [int] $Concurrency = 2
)

$ErrorActionPreference = 'Stop'

if (-not $ProjectRoot) {
    $here = if ($PSScriptRoot) { $PSScriptRoot }
            elseif ($MyInvocation.MyCommand.Path) {
                Split-Path -Parent $MyInvocation.MyCommand.Path
            }
            else { (Get-Location).Path }
    $ProjectRoot = Split-Path -Parent $here
}
$ProjectRoot = (Resolve-Path $ProjectRoot).Path
Write-Host "Project root: $ProjectRoot"

$python = Join-Path $ProjectRoot '.venv\Scripts\python.exe'
$backend = Join-Path $ProjectRoot 'backend'
$manage = Join-Path $backend 'manage.py'

# Find FFmpeg now, while running as a real user who can see it. The service
# account cannot, so the answer has to be baked into the wrapper.
$ffmpegDir = ''
$ffmpegCmd = Get-Command ffmpeg.exe -ErrorAction SilentlyContinue
if ($ffmpegCmd) {
    $ffmpegDir = Split-Path -Parent $ffmpegCmd.Source
} else {
    $wingetPackages = Join-Path $env:LOCALAPPDATA 'Microsoft\WinGet\Packages'
    if (Test-Path $wingetPackages) {
        $found = Get-ChildItem -Path $wingetPackages -Filter 'ffmpeg.exe' -Recurse `
            -ErrorAction SilentlyContinue | Select-Object -First 1
        if ($found) { $ffmpegDir = $found.DirectoryName }
    }
}
if ($ffmpegDir) {
    Write-Host "FFmpeg: $ffmpegDir"
} else {
    Write-Warning 'FFmpeg was not found. Warming will fail at audio extraction.'
}

foreach ($required in @($python, $manage)) {
    if (-not (Test-Path $required)) {
        throw "Not found: $required. Pass -ProjectRoot with the repository root."
    }
}

# Somewhere durable for the log. The task runs as SYSTEM at boot, which has
# no user profile to write into.
$logDir = if ($env:PROGRAMDATA -and (Test-Path $env:PROGRAMDATA)) {
    Join-Path $env:PROGRAMDATA 'transcription'
} else {
    Join-Path $env:LOCALAPPDATA 'transcription'
}
if (-not (Test-Path $logDir)) {
    New-Item -ItemType Directory -Path $logDir -Force | Out-Null
}
$logFile = Join-Path $logDir 'eagle-cycle.log'

# A wrapper, because a scheduled task action cannot itself redirect output
# or set environment variables.
$wrapper = Join-Path $logDir 'run-eagle-cycle.ps1'
@"
# Generated by install-windows-task.ps1. Edit the values below to retune.
`$env:DJANGO_SETTINGS_MODULE = 'transcription_proj.settings'
`$env:PYTHONUNBUFFERED = '1'

# Below the provider's per-minute ceiling: being refused costs a whole
# revision, and warming has no deadline that would justify the risk.
`$env:AI_MAX_REQUESTS_PER_MINUTE = '15'

# THE DATABASE MUST BE NAMED, because settings.py defaults to SQLITE.
#
# Without this the poller runs perfectly against a local sqlite file while
# the application serves Postgres: the log fills with healthy-looking
# [sync:...] lines and the queue never changes. Worse, select_for_update --
# which the claim guard depends on -- is a silent no-op on SQLite, so the
# protection against two workers taking one task would quietly stop
# existing.
`$env:DB_ENGINE = 'postgres'

# Django's own logging writes non-ASCII (task titles, French text). Under
# the SYSTEM account the console codepage is cp1252 and an accented
# character raises UnicodeEncodeError mid-cycle.
`$env:PYTHONUTF8 = '1'

# WHERE FFMPEG IS, because SYSTEM cannot see a per-user install.
#
# winget puts FFmpeg under the installing user's LOCALAPPDATA. The service
# runs as SYSTEM, whose LOCALAPPDATA is elsewhere, so the pipeline's own
# discovery finds nothing and every warm fails at audio extraction. This is
# resolved at INSTALL time, in the operator's session, where it is visible.
`$env:FFMPEG_DIR = '$ffmpegDir'

# STALE, AND NOW A NO-OP. The verbatim standard pass reads
# EAGLE_STANDARD_QUALITY_PROFILE and defaults to 'eagle_standard' -- a
# profile that omits the source-fidelity audit, because that audit reported
# the pass's own required edits as defects and reverted them.
# `$env:EAGLE_WARM_QUALITY_PROFILE = 'volume'

Set-Location '$backend'
& '$python' manage.py eagle_cycle --loop --interval $IntervalSeconds ``
    --pool-size $PoolSize --concurrency $Concurrency *>> '$logFile'
"@ | Set-Content -Path $wrapper -Encoding utf8

if (Get-ScheduledTask -TaskName $TaskName -ErrorAction SilentlyContinue) {
    Write-Host "Replacing the existing '$TaskName' task."
    Unregister-ScheduledTask -TaskName $TaskName -Confirm:$false
}

$action = New-ScheduledTaskAction `
    -Execute 'powershell.exe' `
    -Argument "-NoProfile -ExecutionPolicy Bypass -WindowStyle Hidden -File `"$wrapper`""

# WITH ADMIN: at boot, as SYSTEM, so the queue is current before anyone
# signs in and the poller runs whether or not a person is logged on.
#
# WITHOUT ADMIN: at logon, as the current user. Registering a SYSTEM task
# needs elevation, and refusing to install anything at all would leave the
# real problem -- a poller that dies with the terminal -- unsolved for the
# sake of a trigger that fires a few seconds earlier. The logon task
# survives reboots, which is what actually matters.
$identity = [Security.Principal.WindowsIdentity]::GetCurrent()
$elevated = (New-Object Security.Principal.WindowsPrincipal($identity)).IsInRole(
    [Security.Principal.WindowsBuiltInRole]::Administrator)

if ($elevated) {
    $trigger = New-ScheduledTaskTrigger -AtStartup
    $principal = New-ScheduledTaskPrincipal `
        -UserId 'SYSTEM' -LogonType ServiceAccount -RunLevel Highest
    $mode = 'at boot, as SYSTEM'
}
else {
    Write-Host ''
    Write-Host 'Not running as Administrator.' -ForegroundColor Yellow
    Write-Host 'Installing a per-user task that starts at logon instead.'
    Write-Host 'Re-run this elevated for a boot-time SYSTEM task.'
    Write-Host ''
    $trigger = New-ScheduledTaskTrigger -AtLogOn -User $identity.Name
    $principal = New-ScheduledTaskPrincipal `
        -UserId $identity.Name -LogonType Interactive -RunLevel Limited
    $mode = "at logon, as $($identity.Name)"
}

$settings = New-ScheduledTaskSettingsSet `
    -AllowStartIfOnBatteries `
    -DontStopIfGoingOnBatteries `
    -StartWhenAvailable `
    -RestartInterval (New-TimeSpan -Minutes 1) `
    -RestartCount 999 `
    -ExecutionTimeLimit ([TimeSpan]::Zero) `
    -MultipleInstances IgnoreNew

# ExecutionTimeLimit of zero means "no limit". The default is three days,
# after which Windows would kill the poller and nothing would say why.
# MultipleInstances IgnoreNew stops a restart stacking a second poller on
# top of one that is still running -- two of them would race each other for
# the same tasks.

Register-ScheduledTask `
    -TaskName $TaskName `
    -Action $action `
    -Trigger $trigger `
    -Principal $principal `
    -Settings $settings `
    -Description 'Polls Eagle for tasks, retires ones that have gone, and pre-processes a few so workers can claim work that is already transcribed.' | Out-Null

Start-ScheduledTask -TaskName $TaskName

Write-Host ""
Write-Host "Installed and started '$TaskName' -- $mode."
Write-Host "  log      : $logFile"
Write-Host "  wrapper  : $wrapper"
Write-Host ""
Write-Host "Watch it:"
Write-Host "  Get-Content '$logFile' -Tail 40 -Wait"
Write-Host ""
Write-Host "It survives reboots. It does NOT survive the machine's public IP"
Write-Host "changing -- on a mobile hotspot that invalidates the Cloudflare"
Write-Host "clearance every few hours, and only a browser can earn a new one."
Write-Host "Watch for '[NETWORK] public IP changed' in the log."
